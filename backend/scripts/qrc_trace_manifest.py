"""Checksum manifest of the raw reservoir traces for archiving (Zenodo).

The traces (per-step FID waveforms, learned encoders, feature matrices) are gitignored
under backend/artifacts/; this records every file's SHA-256 and size so the archived copy
can be verified against what the committed results were computed from.

Writes docs/QRC/data/TRACES_MANIFEST.json (every file) and TRACES_MANIFEST.md (summary
per run directory, kinds of file, archive-size note).

  python scripts/qrc_trace_manifest.py
"""
from __future__ import annotations

import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.qrc.provenance import provenance  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "artifacts"
DATA = ROOT.parent / "docs/QRC/data"
DIRS = ("traces", "qrc_runs")
SUFFIXES = {".npz", ".pt", ".json", ".log", ".txt", ".csv"}


def sha256(p, chunk=1 << 22):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(chunk), b""):
            h.update(b)
    return h.hexdigest()


def kind(p):
    n = p.name
    if n.startswith(("trace", "learned_encoding_fid")) or "fid" in n and p.suffix == ".npz":
        return "raw FID trace"
    if n.startswith("X") and p.suffix == ".npz":
        return "features (recomputable from trace)"
    if p.suffix == ".pt":
        return "learned encoder"
    if "pred" in n and p.suffix == ".npz":
        return "test predictions"
    if p.suffix == ".npz":
        return "other array"
    return "result / log"


def main():
    files = sorted(f for d in DIRS for f in (ART / d).rglob("*") if f.is_file() and f.suffix in SUFFIXES
                   and ".ckpt" not in f.parts)
    rows = []
    for i, f in enumerate(files, 1):
        rows.append({"path": f.relative_to(ART).as_posix(), "bytes": f.stat().st_size, "sha256": sha256(f),
                     "kind": kind(f)})
        if i % 50 == 0:
            print(f"  {i}/{len(files)}", flush=True)
    out = {"root": "backend/artifacts", "n_files": len(rows), "total_bytes": sum(r["bytes"] for r in rows),
           "files": rows, "provenance": provenance(step="trace checksum manifest")}
    (DATA / "TRACES_MANIFEST.json").write_text(json.dumps(out, indent=1), encoding="utf-8")

    by_run, by_kind = defaultdict(lambda: [0, 0]), defaultdict(lambda: [0, 0])
    for r in rows:
        parts = r["path"].split("/")
        run = "/".join(parts[:2]) if parts[0] == "traces" or len(parts) < 3 else "/".join(parts[:2])
        by_run[run][0] += 1; by_run[run][1] += r["bytes"]
        by_kind[r["kind"]][0] += 1; by_kind[r["kind"]][1] += r["bytes"]
    gb = lambda b: f"{b / 1e9:.2f}"  # noqa: E731
    md = ["# Raw trace manifest (archive checksums)", "",
          f"Generated by `backend/scripts/qrc_trace_manifest.py`. {len(rows)} files, "
          f"{gb(out['total_bytes'])} GB under `backend/artifacts/` (gitignored). Per-file SHA-256 in "
          "`TRACES_MANIFEST.json`.", "",
          "## By kind", "", "| kind | files | GB |", "|---|---|---|"]
    md += [f"| {k} | {n} | {gb(b)} |" for k, (n, b) in sorted(by_kind.items(), key=lambda x: -x[1][1])]
    md += ["", "## By run directory", "", "| run | files | GB |", "|---|---|---|"]
    md += [f"| `{k}` | {n} | {gb(b)} |" for k, (n, b) in sorted(by_run.items())]
    (DATA / "TRACES_MANIFEST.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} files, {gb(out['total_bytes'])} GB")


if __name__ == "__main__":
    main()
